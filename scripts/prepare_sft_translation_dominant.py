#!/usr/bin/env python3
"""prepare_sft_translation_dominant.py — Build balanced, high-quality SFT.

Sources (ALL clean, verified):
    - sft_translation_large.jsonl  — large EN<->JA parallel corpus (Tatoeba +
        OpenSubtitles + KFTT + wikimedia), already templated both directions.
        Generated by scripts/fetch_parallel_enja.py + scripts/build_sft_translation.py.
    - sft_facts_curated.jsonl      — hand-curated verified facts (JA + EN Q&A).
    - optional generated fact dirs — sampled fact QA rows from oversampled fact
        datasets such as sft_facts_combined_300k_v5.

No artificial cap: all clean parallel data is used, plus a small fact mix so
the model retains general knowledge. Held-out translation eval rows are kept in
a SEPARATE file (sft_translation_eval.jsonl) and intentionally NOT included
here so correctness can be measured on novel sentences.

Output defaults to: sft_data/sft_translation_focused/train.jsonl
"""

import argparse
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SFT_CLEAN = ROOT / "sft_data" / "sft_clean"
OUT_DIR = ROOT / "sft_data" / "sft_translation_focused"
OUT_FILE = OUT_DIR / "train.jsonl"

DEFAULT_TRANSLATION_FRAC = 0.90   # ~90% translation, ~10% facts

# Primary translation file: already templated, both directions, deduped.
TRANSLATION_FILES = [
    "sft_translation_large.jsonl",
]
# Fact files (only curated, verified facts).
FACT_FILES = [
    "sft_facts_curated.jsonl",
]


def parse_csv_list(raw):
    return [item.strip() for item in (raw or "").split(",") if item.strip()]


def parse_category_set(raw):
    return {item.strip() for item in parse_csv_list(raw)}


def resolve_clean_or_root(raw):
    path = Path(raw).expanduser()
    if path.is_absolute():
        return path
    clean_candidate = SFT_CLEAN / raw
    if clean_candidate.exists():
        return clean_candidate
    return ROOT / raw


def resolve_output_dir(raw):
    path = Path(raw).expanduser()
    if path.is_absolute():
        return path
    return ROOT / raw


def extract_text(line):
    try:
        return json.loads(line).get("text", line)
    except json.JSONDecodeError:
        return line


def parse_json_line(line):
    try:
        return json.loads(line)
    except json.JSONDecodeError:
        return None


def load_jsonl(path):
    rows = []
    if path.exists():
        with open(path, encoding="utf-8") as f:
            rows = [l.strip() for l in f if l.strip()]
    return rows


def load_translation_rows(paths):
    translation = []
    for raw in paths:
        path = resolve_clean_or_root(raw)
        rows = load_jsonl(path)
        kept = [row for row in rows if '"lang": "en-ja"' in row or '"lang": "ja-en"' in row]
        translation.extend(kept)
        print(f"  translation from {path}: {len(rows)} -> {len(kept)} en-ja/ja-en rows")
    return translation


def load_fact_rows(paths):
    facts = []
    for raw in paths:
        path = resolve_clean_or_root(raw)
        rows = load_jsonl(path)
        facts.extend(rows)
        print(f"  curated facts from {path}: {len(rows)}")
    return facts


def load_extra_fact_rows(dirs):
    extra = []
    for raw in dirs:
        path = resolve_clean_or_root(raw)
        fact_file = path / "train.jsonl" if path.is_dir() else path
        rows = load_jsonl(fact_file)
        kept = []
        for line in rows:
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            if record.get("lang") not in {"en", "ja"}:
                continue
            if record.get("task") not in {"fact_qa", "instruction"}:
                continue
            if record.get("task") == "fact_qa" or record.get("category"):
                kept.append(line)
        extra.extend(kept)
        print(f"  generated facts from {fact_file}: {len(rows)} -> {len(kept)} fact rows")
    return extra


def dedupe_rows(lines):
    seen = set()
    deduped = []
    for line in lines:
        text = extract_text(line)
        if text in seen:
            continue
        seen.add(text)
        deduped.append(line)
    return deduped


def partition_extra_facts(extra_facts, en_repair_categories, ja_protect_categories):
    buckets = {"en_repair": [], "ja_protect": [], "general": []}
    for line in extra_facts:
        record = parse_json_line(line)
        if not record:
            continue
        category = record.get("category")
        lang = record.get("lang")
        if lang == "en" and category in en_repair_categories:
            buckets["en_repair"].append(line)
        elif lang == "ja" and category in ja_protect_categories:
            buckets["ja_protect"].append(line)
        else:
            buckets["general"].append(line)
    return buckets


def take_weighted_rows(rows, n_rows, rng):
    if n_rows <= 0 or not rows:
        return []
    if len(rows) >= n_rows:
        rows = list(rows)
        rng.shuffle(rows)
        return rows[:n_rows]
    out = list(rows)
    while len(out) < n_rows:
        out.append(rng.choice(rows))
    rng.shuffle(out)
    return out


def select_fact_rows(curated_facts, extra_facts, translation_rows, translation_frac, rng,
                     en_repair_categories=None, ja_protect_categories=None,
                     en_repair_share=0.50, ja_protect_share=0.25):
    curated_facts = dedupe_rows(curated_facts)
    curated_texts = {extract_text(line) for line in curated_facts}
    extra_facts = [line for line in extra_facts if extract_text(line) not in curated_texts]
    en_repair_categories = en_repair_categories or set()
    ja_protect_categories = ja_protect_categories or set()

    if translation_frac >= 1.0:
        return curated_facts + extra_facts, {
            "curated_used": len(curated_facts),
            "en_repair_used": 0,
            "ja_protect_used": 0,
            "general_used": len(extra_facts),
            "target_fact_rows": 0,
        }

    target_fact_rows = int(len(translation_rows) * (1 - translation_frac) / max(translation_frac, 1e-9))
    if target_fact_rows <= 0:
        return [], {
            "curated_used": 0,
            "en_repair_used": 0,
            "ja_protect_used": 0,
            "general_used": 0,
            "target_fact_rows": 0,
        }

    if len(curated_facts) >= target_fact_rows:
        rng.shuffle(curated_facts)
        return curated_facts[:target_fact_rows], {
            "curated_used": target_fact_rows,
            "en_repair_used": 0,
            "ja_protect_used": 0,
            "general_used": 0,
            "target_fact_rows": target_fact_rows,
        }

    remaining = max(0, target_fact_rows - len(curated_facts))
    buckets = partition_extra_facts(extra_facts, en_repair_categories, ja_protect_categories)
    en_target = int(remaining * en_repair_share) if en_repair_categories else 0
    ja_target = int(remaining * ja_protect_share) if ja_protect_categories else 0
    en_rows = take_weighted_rows(buckets["en_repair"], en_target, rng)
    ja_rows = take_weighted_rows(buckets["ja_protect"], ja_target, rng)
    used = len(en_rows) + len(ja_rows)
    fallback_source = buckets["general"] + buckets["en_repair"] + buckets["ja_protect"]
    general_rows = take_weighted_rows(fallback_source, max(0, remaining - used), rng)
    return curated_facts + en_rows + ja_rows + general_rows, {
        "curated_used": len(curated_facts),
        "en_repair_used": len(en_rows),
        "ja_protect_used": len(ja_rows),
        "general_used": len(general_rows),
        "target_fact_rows": target_fact_rows,
    }


def write_jsonl(path, rows):
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(r + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out_dir", default="sft_data/sft_translation_focused",
                    help="output dir relative to repo root or absolute path")
    ap.add_argument("--translation_frac", type=float, default=DEFAULT_TRANSLATION_FRAC,
                    help="share of translation rows in the final combined dataset")
    ap.add_argument("--translation_files", default=",".join(TRANSLATION_FILES),
                    help="comma-separated translation jsonl files")
    ap.add_argument("--fact_files", default=",".join(FACT_FILES),
                    help="comma-separated curated fact jsonl files")
    ap.add_argument("--extra_fact_dirs", default="",
                    help="comma-separated fact dataset dirs or jsonl files to sample additional fact QA rows from")
    ap.add_argument("--en_repair_categories", default="",
                    help="comma-separated EN categories to prioritize in Stage 2 fact replay")
    ap.add_argument("--ja_protect_categories", default="",
                    help="comma-separated JA categories to keep protected in Stage 2 fact replay")
    ap.add_argument("--en_repair_share", type=float, default=0.50,
                    help="share of non-curated fact replay budget reserved for EN repair categories")
    ap.add_argument("--ja_protect_share", type=float, default=0.25,
                    help="share of non-curated fact replay budget reserved for JA protected categories")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    out_dir = resolve_output_dir(args.out_dir)
    out_file = out_dir / "train.jsonl"
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)

    translation = load_translation_rows(parse_csv_list(args.translation_files))
    print(f"  translation rows total: {len(translation)}")

    curated_facts = load_fact_rows(parse_csv_list(args.fact_files))
    print(f"  curated facts total: {len(curated_facts)}")

    extra_fact_dirs = parse_csv_list(args.extra_fact_dirs)
    extra_facts = load_extra_fact_rows(extra_fact_dirs) if extra_fact_dirs else []
    if extra_fact_dirs:
        print(f"  generated facts total: {len(extra_facts)}")

    en_repair_categories = parse_category_set(args.en_repair_categories)
    ja_protect_categories = parse_category_set(args.ja_protect_categories)

    facts, fact_summary = select_fact_rows(
        curated_facts, extra_facts, translation, args.translation_frac, rng,
        en_repair_categories=en_repair_categories,
        ja_protect_categories=ja_protect_categories,
        en_repair_share=args.en_repair_share,
        ja_protect_share=args.ja_protect_share,
    )
    print(
        f"  selected fact rows: {len(facts)} "
        f"(curated={fact_summary['curated_used']}, "
        f"en_repair={fact_summary['en_repair_used']}, "
        f"ja_protect={fact_summary['ja_protect_used']}, "
        f"general={fact_summary['general_used']}, "
        f"target={fact_summary['target_fact_rows']})"
    )

    translation = dedupe_rows(translation)
    combined = translation + facts
    rng.shuffle(combined)

    write_jsonl(out_file, combined)

    enja = 0
    for line in combined:
        try:
            if json.loads(line).get("lang") in ("en-ja", "ja-en"):
                enja += 1
        except json.JSONDecodeError:
            pass
    print(f"\n{'='*60}")
    print(f"Final SFT dataset:")
    print(f"  Translation rows: {enja} ({enja/len(combined)*100:.0f}%)")
    print(f"  Facts/other:      {len(combined)-enja}")
    print(f"  Total rows:       {len(combined)}")
    print(f"  Output: {out_file}")
    print(f"{'='*60}")
    print(f"\nHeld-out eval set (novel sentences, NOT in train):")
    ep = SFT_CLEAN / "sft_translation_eval.jsonl"
    if ep.exists():
        print(f"  {ep}: {sum(1 for _ in open(ep, encoding='utf-8'))} rows")


if __name__ == "__main__":
    main()