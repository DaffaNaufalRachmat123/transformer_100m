#!/usr/bin/env python3
"""prepare_sft_translation_dominant.py — Build balanced, high-quality SFT.

Sources (ALL clean, verified):
  - sft_translation_large.jsonl  — large EN<->JA parallel corpus (Tatoeba +
    OpenSubtitles + KFTT + wikimedia), already templated both directions.
    Generated by scripts/fetch_parallel_enja.py + scripts/build_sft_translation.py.
  - sft_facts_curated.jsonl       — hand-curated verified facts (JA + EN Q&A).

No artificial cap: all clean parallel data is used, plus a small fact mix so
the model retains general knowledge. Held-out translation eval rows are kept in
a SEPARATE file (sft_translation_eval.jsonl) and intentionally NOT included
here so correctness can be measured on novel sentences.

Output: sft_data/sft_translation_focused/train.jsonl
"""

import json
import random
from pathlib import Path

RNG = random.Random(42)
ROOT = Path(__file__).resolve().parent.parent
SFT_CLEAN = ROOT / "sft_data" / "sft_clean"
OUT_DIR = ROOT / "sft_data" / "sft_translation_focused"
OUT_FILE = OUT_DIR / "train.jsonl"

TRANSLATION_FRAC = 0.90   # ~90% translation, ~10% facts
FACT_KEYS = ["capital", "tallest", "highest", "population", "largest", "longest",
             "首都", "人口", "で一番", "通貨", "化学式", "ibukota"]

# Primary translation file: already templated, both directions, deduped.
TRANSLATION_FILES = [
    "sft_translation_large.jsonl",
]
# Fact files (only curated, verified facts).
FACT_FILES = [
    "sft_facts_curated.jsonl",
]


def load_jsonl(path):
    rows = []
    if path.exists():
        with open(path, encoding="utf-8") as f:
            rows = [l.strip() for l in f if l.strip()]
    return rows


def is_fact_key(word):
    low = word.lower()
    return any(k in low for k in FACT_KEYS)


def write_jsonl(path, rows):
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(r + "\n")


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Translation rows (already templated, both directions).
    translation = []
    for fname in TRANSLATION_FILES:
        rows = load_jsonl(SFT_CLEAN / fname)
        kept = [r for r in rows if '"lang": "en-ja"' in r or '"lang": "ja-en"' in r]
        translation.extend(kept)
        print(f"  {fname}: {len(rows)} -> {len(kept)} en-ja/ja-en rows")
    print(f"  translation rows: {len(translation)}")

    # 2. Facts (curated verified facts only).
    facts = []
    for fname in FACT_FILES:
        rows = load_jsonl(SFT_CLEAN / fname)
        facts.extend(rows)
        print(f"  facts from {fname}: {len(rows)}")
    print(f"  facts total: {len(facts)}")

    # 3. Down-sample the larger side to keep the promised ratio.
    if TRANSLATION_FRAC < 1.0:
        n_trans_target = len(translation)
        n_fact_target = int(n_trans_target * (1 - TRANSLATION_FRAC) / TRANSLATION_FRAC)
        if len(facts) > n_fact_target:
            RNG.shuffle(facts)
            facts = facts[:n_fact_target]
            print(f"  facts downsampled to {len(facts)} for {TRANSLATION_FRAC:.0%} ratio")

    # 4. Combine, dedup, shuffle.
    seen = set()
    deduped = []
    for line in translation + facts:
        try:
            text = json.loads(line).get("text", line)
        except json.JSONDecodeError:
            text = line
        if text in seen:
            continue
        seen.add(text)
        deduped.append(line)
    RNG.shuffle(deduped)

    write_jsonl(OUT_FILE, deduped)

    enja = 0
    for line in deduped:
        try:
            if json.loads(line).get("lang") in ("en-ja", "ja-en"):
                enja += 1
        except json.JSONDecodeError:
            pass
    print(f"\n{'='*60}")
    print(f"Final SFT dataset:")
    print(f"  Translation rows: {enja} ({enja/len(deduped)*100:.0f}%)")
    print(f"  Facts/other:      {len(deduped)-enja}")
    print(f"  Total rows:       {len(deduped)}")
    print(f"  Output: {OUT_FILE}")
    print(f"{'='*60}")
    print(f"\nHeld-out eval set (novel sentences, NOT in train):")
    ep = SFT_CLEAN / "sft_translation_eval.jsonl"
    if ep.exists():
        print(f"  {ep}: {sum(1 for _ in open(ep, encoding='utf-8'))} rows")


if __name__ == "__main__":
    main()